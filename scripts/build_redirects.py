#!/usr/bin/env python3
"""Generate Netlify `_redirects` from affiliates.json.

Every affiliate link on the site points to /go/<slug>. This script turns
affiliates.json into 302 redirects, appending each program's tracking
parameter when an ID is set. Run locally or let Netlify run it on deploy.
"""
import json
import os
from urllib.parse import urlsplit, urlunsplit, parse_qsl, urlencode

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def with_param(url, key, value):
    parts = urlsplit(url)
    query = [(k, v) for k, v in parse_qsl(parts.query, keep_blank_values=True) if k != key]
    query.append((key, value))
    return urlunsplit(parts._replace(query=urlencode(query, safe="%+")))


def main():
    with open(os.path.join(ROOT, "affiliates.json"), encoding="utf-8") as f:
        config = json.load(f)
    programs = config["programs"]

    lines = [
        "# GENERATED by scripts/build_redirects.py from affiliates.json — edit that file, not this one.",
    ]
    missing = []
    for slug, link in config["links"].items():
        program = programs[link["program"]]
        dest = link.get("override") or link["url"]
        if not link.get("override"):
            if program.get("param") and program.get("id"):
                dest = with_param(dest, program["param"], program["id"])
            else:
                missing.append(slug)
        lines.append(f"/go/{slug}  {dest}  302")

    with open(os.path.join(ROOT, "_redirects"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")

    print(f"Wrote {len(config['links'])} redirects to _redirects")
    if missing:
        print("Untracked (no affiliate ID/override yet): " + ", ".join(missing))


if __name__ == "__main__":
    main()
